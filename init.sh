#!/usr/bin/env bash
# Bootstrap and verify the dev environment at the start of every agent session.
# Exit 0 means the environment is ready; anything else must be fixed before new work.
set -euo pipefail

cd "$(dirname "$0")"

step() { printf '\n[%s/5] %s\n' "$1" "$2"; }

check_writable() {
  local dir="$1"
  local probe
  if mkdir -p "$dir" 2>/dev/null && probe="$(mktemp "$dir/.init-write-test.XXXXXX" 2>/dev/null)"; then
    rm -f "$probe"
    return 0
  fi
  {
    echo "ERROR: cache directory is not writable: $dir"
    echo "Check that .claude/settings.json lists it in sandbox.filesystem.allowWrite,"
    echo "and that .claude/settings.local.json does not point it elsewhere via env."
    echo "Agents cannot edit these files: stop and ask the human to fix them."
  } >&2
  exit 1
}

step 1 "Check cache directories"
uv_cache="$(uv cache dir)"
pre_commit_home="${PRE_COMMIT_HOME:-${XDG_CACHE_HOME:-$HOME/.cache}/pre-commit}"
check_writable "$uv_cache"
check_writable "$pre_commit_home"
echo "uv: $uv_cache"
echo "pre-commit: $pre_commit_home"

step 2 "uv sync"
uv sync --frozen

step 3 "pre-commit install"
# The sandbox denies writes to .git/hooks, so install only when the hooks are missing.
hooks_dir="$(git rev-parse --git-path hooks)"
if grep -qs "File generated by pre-commit" "$hooks_dir/pre-commit" &&
  grep -qs "File generated by pre-commit" "$hooks_dir/commit-msg"; then
  echo "already installed"
elif ! uv run --frozen pre-commit install; then
  {
    echo "ERROR: could not install git hooks into $hooks_dir"
    echo "Agents cannot write there inside the sandbox: stop and ask the human"
    echo "to run 'uv run pre-commit install' outside the sandbox."
  } >&2
  exit 1
fi

step 4 "pre-commit run --all-files"
uv run --frozen pre-commit run --all-files

step 5 "pytest"
# -print -quit avoids a find | grep pipeline, which pipefail can turn into a false skip via SIGPIPE.
if [ -d tests ] && [ -n "$(find tests \( -name 'test_*.py' -o -name '*_test.py' \) -print -quit)" ]; then
  uv run --frozen pytest
else
  echo "skip (no tests)"
fi

echo
echo "Next: read claude-progress.md (latest session) and feature_list.json"
